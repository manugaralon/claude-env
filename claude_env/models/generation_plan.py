"""GenerationPlan Pydantic v2 model — output contract of the pipeline planning step."""
from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, ConfigDict


class OutputLayer(StrEnum):
    """Where a generated artifact is installed."""

    GLOBAL = "global"
    PROJECT = "project"
    # PROJECT_ROOT writes outside .claude/ — at the project root itself.
    # Used for files Claude Code reads from the repo root (e.g. .mcp.json).
    PROJECT_ROOT = "project_root"


class MergeStrategy(StrEnum):
    """How the generator writes an artifact against an existing target.

    The strategy is explicit metadata on the Artifact — never inferred from
    file contents (Phase-3 invariant). When `merge_strategy` is unset the
    generator maps it from `layer`/`write_once` for backward compatibility.
    """

    # Replace the target unconditionally (generated machine config).
    OVERWRITE = "overwrite"
    # Inject/refresh a sentinel-wrapped managed block; surrounding user
    # content is byte-preserved (e.g. an existing bespoke CLAUDE.md).
    SENTINEL = "sentinel"
    # Create once; never touch an existing target (e.g. CONSTITUTION.md).
    WRITE_ONCE = "write_once"
    # Create only when absent; leave hand-editable files untouched
    # (e.g. CONTEXT.md, skills, agents).
    SKIP_IF_EXISTS = "skip_if_exists"


class Artifact(BaseModel):
    """A single file to be generated by the TemplateRegistry."""

    model_config = ConfigDict(extra="forbid")

    target_path: str
    template_id: str
    context: dict[str, object]
    layer: OutputLayer
    # When True, the generator skips this artifact if the target already exists,
    # leaving user-owned content (e.g. CONSTITUTION.md) byte-untouched.
    # Retained for backward compatibility; equivalent to
    # merge_strategy=MergeStrategy.WRITE_ONCE.
    write_once: bool = False
    # Explicit write strategy. When None, the generator derives it from
    # `layer`/`write_once` so pre-existing artifacts keep identical behavior.
    merge_strategy: MergeStrategy | None = None


class GenerationPlan(BaseModel):
    """Full generation plan produced by the pipeline for a given ProjectSpec."""

    model_config = ConfigDict(extra="forbid")

    project_name: str
    domain: str
    artifacts: list[Artifact]
